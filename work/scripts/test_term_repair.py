# -*- coding: utf-8 -*-
r"""term_repair.py 的单元测试（源语驱动称谓修复）。

运行：python test_term_repair.py
"""
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.stdout.reconfigure(encoding="utf-8")

import term_repair as tr   # noqa: E402

CASES = [
    # (中文, 日文, 期望, 说明)
    # ---- 规则 1：源语无指示词 → 删中文多出的「这位/那位」 ----
    ("这位先生似乎更喜欢对女性的乳头进行刺激，",
     "違うよね先生はマヤの乳首攻めと", "老师似乎更喜欢对女性的乳头进行刺激，",
     "先生は（无指示词）→ 删「这位」"),
    ("那位先生好像不太高兴。", "先生は不機嫌そう", "老师好像不太高兴。",
     "先生は（无指示词）→ 删「那位」"),
    ("某位先生来了。", "先生が来た", "老师来了。",
     "先生が（无指示词）→ 删「某位」"),
    # ---- 规则 2：源语有指示词 → 保留指示词 ----
    ("这位先生真厉害！", "この先生はすごい", "这位老师真厉害！",
     "この先生 → 保留「这位」"),
    ("那位先生在哪里？", "あの先生はどこ", "那位老师在哪里？",
     "あの先生 → 保留「那位」"),
    # ---- 规则 3：裸「先生」→ 锚点 ----
    ("考虑到先生一直以来的行为，", "先生が今までしてきたことを考えると",
     "考虑到老师一直以来的行为，", "裸先生 → 老师"),
    ("先生的胸部！", "先生のおっぱい!", "老师的胸部！", "裸先生 → 老师"),
    ("先生 您更喜欢哪边的乳房？", "先生はどっちが好き", "老师 您更喜欢哪边的乳房？",
     "句首先生 → 老师"),
    # ---- 专名保护 ----
    ("我的学生 哈拉玛老师", "教え子ハラマ先生", "我的学生 哈拉玛老师",
     "人名+先生（专名）不动"),
    ("我的学生 哈拉玛先生", "教え子ハラマ先生", "我的学生 哈拉玛先生",
     "专名里的先生不动，即使写成「先生」"),
    # ---- 不动的情况 ----
    ("老公 你回来啦", "旦那", "老公 你回来啦", "源语无先生不动"),
    ("就这样紧紧抱住了老师。", "ぎゅっと先生を抱きしめた", "就这样紧紧抱住了老师。",
     "已是「老师」不动"),
    ("老师您做得真棒啊！", "先生 お上手", "老师您做得真棒啊！", "已是老师不动"),
    # ---- 边界：源语先生但其实指别处 ----
    ("啊 老师 您好。", "あ 先生 こんにちは", "啊 老师 您好。", "已是老师"),
    # ---- 昵称/爱称保护（用户 2026-10-16 指出「肛门先生」是调情式昵称）----
    ("按照「肛门先生」的命令，", "アナル先生の命令で", "按照「肛门先生」的命令，",
     "引号内昵称不动"),
    ("肛门先生 你好厉害", "アナル先生", "肛门先生 你好厉害", "戏称前缀不动"),
    ("屁股先生 快来", "お尻先生", "屁股先生 快来", "戏称前缀不动"),
]

# ---- 多族测试：把 zh_variants 传进去（模拟账本多族）----
# (中文, 日文, 日文别名正则, 锚点, 变体池, 期望, 说明)
MULTI_CASES = [
    ("老哥 你在哪？", "お兄ちゃん どこ", r"お?兄(さん|ちゃん|ち|さ)", "哥哥",
     ["哥哥", "老哥"], "お兄ちゃん→哥哥（老哥收敛）", "老哥 你在哪？".replace("老哥", "哥哥")),
    ("大姐姐 抱抱", "お姉ちゃん 抱っこ", r"お?姉(さん|ちゃん|ち|さ)", "姐姐",
     ["姐姐", "大姐姐"], "お姉ちゃん→姐姐", "姐姐 抱抱"),
    ("主人大人 请吩咐", "ご主人様 お申し付けを", r"ご?主人様?", "主人",
     ["主人", "主人大人", "老爷"], "ご主人様→主人", "主人 请吩咐"),
    ("没错 前辈说得对", "そうですね 先輩の言う通り", r"先輩", "前辈",
     ["前辈", "学长"], "先輩→前辈（不动）", "没错 前辈说得对"),
    ("老哥 我好喜欢你", "お兄ちゃん 大好き", r"お?兄(さん|ちゃん|ち|さ)", "哥哥",
     ["哥哥", "老哥"], "多族：兄+喜欢", "哥哥 我好喜欢你"),
]


def main():
    ok = 0
    fail = []
    for zh, ja, exp, desc in CASES:
        new, n, _w = tr.repair_line(zh, ja)
        if new == exp:
            ok += 1
            print("  OK   %s" % desc)
        else:
            fail.append(desc)
            print("  FAIL %s" % desc)
            print("       got: %s" % new)
            print("       exp: %s" % exp)

    print("\n--- 多族（带账本变体池）---")
    for zh, ja, alias, anchor, fam, desc, exp in MULTI_CASES:
        new, n, _w = tr.repair_line(zh, ja, anchor, alias, zh_variants=fam)
        if new == exp:
            ok += 1
            print("  OK   %s" % desc)
        else:
            fail.append(desc)
            print("  FAIL %s" % desc)
            print("       got: %s" % new)
            print("       exp: %s" % exp)

    total = len(CASES) + len(MULTI_CASES)
    print("\n%d/%d 通过" % (ok, total))
    if fail:
        print("失败用例：")
        for d in fail:
            print("  - %s" % d)
        sys.exit(1)


if __name__ == "__main__":
    main()
